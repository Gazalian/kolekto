/**
 * Puts the report font where the PDF renderer can load it, and records which
 * characters it can draw.
 *
 * WHY A FONT IS EMBEDDED AT ALL. A PDF's fourteen standard fonts are
 * WinAnsi-encoded, and WinAnsi has no naira sign. A Kolekto report that
 * printed "N10,000" where it means "₦10,000" would be wrong on paper, in the
 * one format people keep precisely because it is the paper record. WinAnsi
 * also cannot write ẹ, ọ, ṣ, ị or ụ, which is to say it cannot write a great
 * many Nigerian names.
 *
 * WHY THE WHOLE FONT AND NOT A SUBSET. The first attempt subsetted DejaVu
 * Sans with fontkit and embedded the ~20 KB result. It does not work:
 * `subset.encode()` emits head, hhea, loca, maxp, cvt, prep, glyf, hmtx and
 * fpgm — and no `name`, `cmap`, `OS/2` or `post`. pdf-lib reads `name.records`
 * and fails with "Cannot read properties of undefined". Rebuilding those
 * tables by hand means rebuilding a cmap against fontkit's remapped glyph
 * ids, which is a font compiler, and a wrong one draws the wrong letters
 * silently. pdf-lib subsets the font itself at embed time anyway, so the
 * PDFs that come out are small either way — the only cost of shipping the
 * whole file is 1.5 MB in the repository.
 *
 * WHY THE FILE IS COPIED INTO public/. It has to be readable by the server
 * at request time, and `public/` is the one directory Next guarantees ends
 * up in the build. The first attempt read it from beside the source file with
 * `new URL(…, import.meta.url)`; that works in development and not in a
 * production build, where the server code is bundled into .next/server/chunks
 * and the .ttf beside the source is nowhere near it. A redistributable font
 * being publicly fetchable costs nothing.
 *
 * Run `node scripts/pdf/build-report-font.mjs` after changing the character
 * set below. It rewrites apps/web/lib/pdf/font-data.ts and refreshes the
 * fonts in apps/web/public/fonts/.
 *
 * Licence: DejaVu Sans is free to use, embed and redistribute — see
 * node_modules/dejavu-fonts-ttf/LICENSE, copied next to the fonts so the
 * notice travels with the bytes.
 */
import * as fontkit from "fontkit";
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";

const ASCII = Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => 0x20 + i);
const LATIN_1 = Array.from({ length: 0xff - 0xa0 + 1 }, (_, i) => 0xa0 + i);
const LATIN_EXT_A = Array.from({ length: 0x17f - 0x100 + 1 }, (_, i) => 0x100 + i);

// Yoruba and Igbo, written with a dot below. These are names, not decoration.
const AFRICAN_LATIN = [
  0x1e62, 0x1e63, // Ṣ ṣ
  0x1e44, 0x1e45, // Ṅ ṅ
  0x1eb8, 0x1eb9, // Ẹ ẹ
  0x1eba, 0x1ebb, 0x1ebc, 0x1ebd, 0x1ebe, 0x1ebf,
  0x1ec0, 0x1ec1, 0x1ec2, 0x1ec3, 0x1ec4, 0x1ec5, 0x1ec6, 0x1ec7,
  0x1eca, 0x1ecb, // Ị ị
  0x1ecc, 0x1ecd, // Ọ ọ
  0x1ece, 0x1ecf, 0x1ed0, 0x1ed1, 0x1ed2, 0x1ed3, 0x1ed4, 0x1ed5,
  0x1ee4, 0x1ee5, // Ụ ụ
  0x1ee6, 0x1ee7, 0x1ee8, 0x1ee9,
  0x0300, 0x0301, 0x0304, 0x0323, // combining grave, acute, macron, dot below
];

const PUNCTUATION = [
  0x2013, 0x2014, // – —
  0x2018, 0x2019, 0x201c, 0x201d, // ' ' " "
  0x2022, 0x2026, 0x00b7, // • … ·
  0x2192, // →
];

const CURRENCY = [0x20a6, 0x00a3, 0x0024, 0x20ac]; // ₦ £ $ €

const WANTED = [...ASCII, ...LATIN_1, ...LATIN_EXT_A, ...AFRICAN_LATIN, ...PUNCTUATION, ...CURRENCY];

const SOURCES = {
  regular: "node_modules/dejavu-fonts-ttf/ttf/DejaVuSans.ttf",
  bold: "node_modules/dejavu-fonts-ttf/ttf/DejaVuSans-Bold.ttf",
};

mkdirSync("apps/web/public/fonts", { recursive: true });
copyFileSync(SOURCES.regular, "apps/web/public/fonts/DejaVuSans.ttf");
copyFileSync(SOURCES.bold, "apps/web/public/fonts/DejaVuSans-Bold.ttf");
copyFileSync("node_modules/dejavu-fonts-ttf/LICENSE", "apps/web/public/fonts/LICENSE");

function coverage(path) {
  const font = fontkit.openSync(path);
  const missing = WANTED.filter((code) => !font.hasGlyphForCodePoint(code));
  if (missing.length > 0) {
    console.warn(`${path}: no glyph for ${missing.map((c) => "U+" + c.toString(16).toUpperCase()).join(" ")}`);
  }
  return WANTED.filter((code) => font.hasGlyphForCodePoint(code));
}

const regular = coverage(SOURCES.regular);
const bold = coverage(SOURCES.bold);

// A code point is usable only if BOTH weights can draw it — a heading and a
// cell must never disagree about whether a name is printable.
const usable = regular.filter((code) => bold.includes(code));

writeFileSync(
  "apps/web/lib/pdf/font-data.ts",
  `/**
 * Which characters a report can print.
 *
 * GENERATED by scripts/pdf/build-report-font.mjs — do not edit by hand.
 *
 * Text is sanitised against this before it reaches the page: pdf-lib throws
 * on a character its font cannot encode, and one unusual character in one
 * member's name must not be the reason a whole committee's report fails to
 * generate. The list is the intersection of what DejaVu Sans and DejaVu Sans
 * Bold can both draw, across printable ASCII, Latin-1, Latin Extended-A, the
 * Yoruba and Igbo letters, the punctuation a word processor substitutes, and
 * ₦.
 */
export const REPORT_FONT_CODE_POINTS: ReadonlySet<number> = new Set([
${usable.map((c) => `  0x${c.toString(16)},`).join("\n")}
]);
`,
  "utf8",
);

console.log(
  `copied DejaVu Sans (regular + bold) into apps/web/public/fonts/, ${usable.length} printable code points`,
);
